import json
from datetime import datetime, timezone
from pathlib import Path

from fastapi import APIRouter, HTTPException
from fastapi.responses import PlainTextResponse, Response

import store
from schemas import Finding

router = APIRouter(prefix="/api/scan", tags=["reports"])


@router.get("/{scan_id}/report/json")
def report_json(scan_id: str) -> Response:
    result = store.get_scan(scan_id)
    if not result:
        raise HTTPException(status_code=404, detail=f"Scan {scan_id!r} not found")

    data = result.model_dump()
    # Attach any cached AI explanations
    for f in data["findings"]:
        exp = store.get_explanation(f["id"])
        if exp:
            f["explanation"] = exp

    payload = json.dumps(data, indent=2, default=str)
    return Response(
        content=payload,
        media_type="application/json",
        headers={"Content-Disposition": f'attachment; filename="{scan_id}-report.json"'},
    )


@router.get("/{scan_id}/report/markdown", response_class=PlainTextResponse)
def report_markdown(scan_id: str) -> str:
    result = store.get_scan(scan_id)
    if not result:
        raise HTTPException(status_code=404, detail=f"Scan {scan_id!r} not found")

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines: list[str] = [
        "# RepoShield AI — Security Report",
        f"\n**Scan ID:** `{result.scan_id}`  ",
        f"**Target:** `{result.target}`  ",
        f"**Generated:** {ts}  ",
        f"**Scanners:** {result.scanner}",
        "\n---\n",
        "## Summary\n",
        f"| Severity | Count |",
        f"|---|---|",
    ]
    s = result.summary
    if s:
        for sev in ("critical", "high", "medium", "low", "info"):
            count = getattr(s, sev, 0)
            if count:
                lines.append(f"| {sev.capitalize()} | {count} |")
        lines.append(f"| **Total** | **{s.total}** |")

    lines += ["\n---\n", "## Findings\n"]

    by_severity = {"critical": [], "high": [], "medium": [], "low": [], "info": []}
    for f in result.findings:
        by_severity.setdefault(f.severity, []).append(f)

    for sev in ("critical", "high", "medium", "low", "info"):
        group: list[Finding] = by_severity.get(sev, [])
        if not group:
            continue
        lines.append(f"### {sev.capitalize()} ({len(group)})\n")
        for f in group:
            lines.append(f"#### `{f.rule_id}`\n")
            lines.append(f"- **File:** `{f.file}:{f.line}`")
            lines.append(f"- **Category:** {f.category}")
            lines.append(f"- **Source:** {f.source}")
            lines.append(f"- **Message:** {f.message}")
            lines.append(f"\n```\n{f.code_excerpt}\n```\n")

            exp = store.get_explanation(f.id)
            if exp:
                lines.append(f"**AI Explanation:** {exp.get('summary', '')}\n")
                if exp.get("remediation"):
                    lines.append(f"**Remediation:** {exp['remediation']}\n")
                if exp.get("patch"):
                    lines.append(f"**Suggested Patch:**\n```\n{exp['patch']}\n```\n")

    if result.error:
        lines += ["\n---\n", f"**Scanner errors:** {result.error}"]

    lines.append(
        "\n---\n*Generated by [RepoShield AI](https://github.com/ashutoshraj163/reposhield-ai)*"
    )

    content = "\n".join(lines)
    return Response(
        content=content,
        media_type="text/markdown",
        headers={"Content-Disposition": f'attachment; filename="{scan_id}-report.md"'},
    )
